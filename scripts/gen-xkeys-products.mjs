#!/usr/bin/env node
/*
 * Writes `src/core/xkeys-products.js` from the X-keys product table in
 * SuperFly.tv's xkeys library (MIT): `packages/core/src/products.ts` in a
 * checkout of github.com/SuperFlyTV/xkeys.
 *
 *     node scripts/gen-xkeys-products.mjs <xkeys checkout> [commit]
 *
 * The table is what Bitfocus Companion drives real X-keys with, and this app
 * copies it rather than re-deriving it from P.I. Engineering's PDFs, for the
 * reason `src/vendor/` exists: two tools must not reach different conclusions
 * about the same panel. Only the panels with keys (or switch inputs) to press
 * are kept — not the serial, DMX, relay, servo, motor, trackball, trackpad,
 * QWERTY or RailDriver devices, which are not control surfaces for a switcher.
 *
 * products.ts is TypeScript with one `enum`, which Node's type stripping
 * refuses, so a copy has the enum turned into an object before it is imported.
 */

import { mkdtemp, readFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, '..', 'src', 'core', 'xkeys-products.js');

const LEFT_OUT = new Set([
  'XKHD15GPIO', 'XCRS232', 'XCDMX512TST', 'XCDMX512TRJ45', 'XBA4X3TRACKBALL', 'XBK_QWERTY',
  'XCDRCSERVO', 'XCRELAY', 'XCMOTORDRIVER', 'XBA4X3TRACKPAD', 'RailDriver',
]);
const KEEP = [
  'name', 'hidDevices', 'bBytes', 'bBits', 'colCount', 'rowCount', 'hasPS', 'backLightType',
  'backLight2offset', 'btnLocation', 'disableButtons', 'timestampByte', 'hasJog', 'hasShuttle',
  'hasTbar', 'hasJoystick',
];

const [checkout, commit = 'unknown'] = process.argv.slice(2);
if (!checkout) {
  console.error('usage: node scripts/gen-xkeys-products.mjs <xkeys checkout> [commit]');
  process.exit(2);
}

const src = join(checkout, 'packages', 'core', 'src');
const scratch = await mkdtemp(join(tmpdir(), 'xkeys-products-'));
try {
  let ts = await readFile(join(src, 'products.ts'), 'utf8');
  ts = ts.replace(/export enum BackLightType \{([\s\S]*?)\n\}/, (_, body) => `export const BackLightType = {${body.replace(/(\w+) = (\d+),/g, '$1: $2,')}\n} as const`);
  ts = ts.replace("from './lib'", "from './lib.ts'");
  await writeFile(join(scratch, 'products.ts'), ts);
  await writeFile(join(scratch, 'lib.ts'), await readFile(join(src, 'lib.ts'), 'utf8'));
  const { PRODUCTS, XKEYS_VENDOR_ID, BackLightType } = await import(pathToFileURL(join(scratch, 'products.ts')).href);

  const products = {};
  for (const [key, p] of Object.entries(PRODUCTS)) {
    if (LEFT_OUT.has(key)) continue;
    const kept = {};
    for (const field of KEEP) if (p[field] !== undefined) kept[field] = p[field];
    products[key] = kept;
  }

  const body = `/*
 * GENERATED by scripts/gen-xkeys-products.mjs — do not edit by hand.
 *
 * The X-keys panels with keys to press, from SuperFly.tv's xkeys library
 * (github.com/SuperFlyTV/xkeys, packages/core/src/products.ts at ${commit}, MIT,
 * Copyright (c) 2017 SuperFly.tv): the table Bitfocus Companion drives real
 * X-keys with. \`src/core/xkeys.js\` reads it; ATTRIBUTIONS.md credits it.
 *
 * Byte numbers are indexes into an input report as node-hid hands it over
 * (byte 0 is the unit id, byte 1 the flags and the program switch, buttons
 * from byte 2). A key's index counts down each column of \`bBits\` keys:
 * index 0 is the program switch, 1 the top of the first column.
 */

export const XKEYS_VENDOR_ID = ${XKEYS_VENDOR_ID};

export const BACKLIGHT = Object.freeze(${JSON.stringify(BackLightType)});

export const PRODUCTS = Object.freeze({
${Object.entries(products).map(([key, p]) => `  ${key}: {\n${Object.entries(p).map(([f, v]) => `    ${f}: ${JSON.stringify(v)},`).join('\n')}\n  },`).join('\n')}
});
`;
  await writeFile(OUT, body);
  console.log(`wrote ${Object.keys(products).length} panels to ${OUT}`);
} finally {
  await rm(scratch, { recursive: true, force: true });
}
