/*
 * Re-copy the Mynah language core from a mynah checkout.
 *
 * The Console panel speaks Mynah's command language. That grammar must be the
 * *same* grammar the standalone tool and the Companion module use — a second
 * transcription of it would drift the first time a keyword moved, and nothing
 * would notice until an operator typed a command that quietly meant something
 * else.
 *
 *   npm run sync:mynah-lang                  looks in ../mynah
 *   npm run sync:mynah-lang -- /path/to/repo
 *
 * Mynah is TypeScript with a Vite build; this repo has none. That is fine,
 * because mynah already builds the language on its own for exactly this —
 * `npm run build:lang` emits `dist-lang/mynah-lang.mjs`, an unminified,
 * dependency-free ES module intended for consumers outside that repo. We
 * vendor the built artefact, not the sources.
 *
 * Same contract as tools/sync-vpu-model.mjs: rewrite the provenance header
 * with the upstream commit and a content hash, so `test/vendor.test.js` can
 * tell a deliberate sync from silent drift.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dest = join(here, '..', 'src', 'vendor', 'mynah-lang.mjs');
const upstreamRepo = resolve(process.argv[2] || join(here, '..', '..', 'mynah'));
const upstreamFile = join(upstreamRepo, 'dist-lang', 'mynah-lang.mjs');

let source;
try {
  source = await readFile(upstreamFile, 'utf8');
} catch {
  console.error(`! no ${upstreamFile}`);
  console.error('  run `npm run build:lang` in the mynah checkout first');
  process.exit(1);
}
const hash = createHash('sha256').update(source).digest('hex');

/*
 * The build output is generated, so its own mtime says nothing. Pin the commit
 * of the SOURCES it was built from instead — that is the thing a reader needs
 * in order to go and look at what this actually is.
 */
let commit = 'unknown';
let dirty = false;
try {
  commit = execFileSync('git', ['-C', upstreamRepo, 'log', '-1', '--format=%H', '--', 'src/lang'],
    { encoding: 'utf8' }).trim();
  dirty = execFileSync('git', ['-C', upstreamRepo, 'status', '--short', '--', 'src/lang'],
    { encoding: 'utf8' }).trim().length > 0;
} catch {
  console.warn('! upstream is not a git checkout; recording commit as unknown');
}

if (dirty) {
  console.error('! upstream src/lang has uncommitted changes — commit there first');
  process.exit(1);
}

const HEADER = `/* ---------------------------------------------------------------------------
 * VENDORED — do not edit this file here.
 *
 * Upstream:  stoatworks-labs/mynah  dist-lang/mynah-lang.mjs
 * Commit:    ${commit}
 * Synced:    ${new Date().toISOString().slice(0, 10)}
 * SHA-256:   ${hash}
 *
 * Mynah's command language: lexer, parser, compiler, keyword table and model.
 * The Console panel is a front-end over this and nothing more — the grammar
 * belongs to mynah, and having two copies of a grammar is having two grammars.
 *
 * This is mynah's own \`npm run build:lang\` output: unminified, no runtime
 * dependencies, and produced specifically for consumers outside that repo (the
 * Companion module vendors the same file). Bundling rather than transcribing is
 * the point — a hand-port would drift the first time a keyword moved.
 *
 * \`npm run sync:mynah-lang\` re-copies it and rewrites the lines above;
 * \`test/vendor.test.js\` fails when the copy has drifted from an upstream
 * checkout, and skips when there is not one to compare with.
 *
 * Edits belong upstream, in mynah's \`src/lang/\`.
 * ------------------------------------------------------------------------- */`;

await writeFile(dest, HEADER + '\n\n' + source);
console.log(`synced from ${upstreamFile}`);
console.log(`  commit ${commit}`);
console.log(`  sha256 ${hash}`);
