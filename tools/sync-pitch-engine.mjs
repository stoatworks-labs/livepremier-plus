/*
 * Re-copy the pitch-compensation engine from an aquilon-pitch checkout.
 *
 * The Pitch panel works out the H and V ratios a screen with mixed-pitch LED
 * walls needs. That arithmetic is small, and it is exactly the kind of small
 * that gets re-typed slightly differently in a second place — the direction of
 * the ratio, the 0.100–10.000 range, and the fact that the device FLOORS the
 * canvas footprint are each one character away from being wrong and still
 * looking right. aquilon-pitch established all three by driving a simulator and
 * pinned them as tests; this repo borrows the result rather than re-deriving it.
 *
 *   npm run sync:pitch-engine                  looks in ../aquilon-pitch
 *   npm run sync:pitch-engine -- /path/to/repo
 *
 * aquilon-pitch is TypeScript with a Vite build; this repo has none. Same
 * arrangement as mynah: it builds a consumer-facing artefact of its own —
 * `npm run build:lib` emits `dist-lib/aquilon-pitch-engine.js`, an unminified,
 * dependency-free ES module — and we vendor that, not the sources.
 *
 * Same contract as tools/sync-vpu-model.mjs and tools/sync-mynah-lang.mjs:
 * rewrite the provenance header with the upstream commit and a content hash, so
 * `test/vendor.test.js` can tell a deliberate sync from silent drift.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dest = join(here, '..', 'src', 'vendor', 'pitch-engine.js');
const upstreamRepo = resolve(process.argv[2] || join(here, '..', '..', 'aquilon-pitch'));
const upstreamFile = join(upstreamRepo, 'dist-lib', 'aquilon-pitch-engine.js');

let source;
try {
  source = await readFile(upstreamFile, 'utf8');
} catch {
  console.error(`! no ${upstreamFile}`);
  console.error('  run `npm run build:lib` in the aquilon-pitch checkout first');
  process.exit(1);
}

const hash = createHash('sha256').update(source).digest('hex');

let commit = 'unknown';
let dirty = false;
try {
  commit = execFileSync('git', ['-C', upstreamRepo, 'log', '-1', '--format=%H', '--', 'dist-lib'],
    { encoding: 'utf8' }).trim();
  dirty = execFileSync('git', ['-C', upstreamRepo, 'status', '--short', '--', 'dist-lib'],
    { encoding: 'utf8' }).trim().length > 0;
} catch {
  console.warn('! upstream is not a git checkout; recording commit as unknown');
}

/* Syncing from a modified working copy records a commit that does not contain
   what was copied. Refuse rather than write a provenance line that lies. */
if (dirty) {
  console.error('! upstream dist-lib/ has uncommitted changes — commit there first');
  process.exit(1);
}

const MARKER = ' * ------------------------------------------------------------------------- */';

const header = `/* ---------------------------------------------------------------------------
 * VENDORED — do not edit this file here.
 *
 * Upstream:  stoatworks-labs/aquilon-pitch  dist-lib/aquilon-pitch-engine.js
 * Commit:    ${commit}
 * Synced:    ${new Date().toISOString().slice(0, 10)}
 * sha256:    ${hash}
 *
 * The pitch-compensation engine, built from aquilon-pitch's src/lib/. Same
 * reasoning as ./vpu-model.js and ./mynah-lang.mjs: one implementation, copied
 * rather than re-derived, so two tools cannot reach different conclusions about
 * the same device.
 *
 * What it knows, and what would be easy to get wrong here:
 *
 *   - the ratio MULTIPLIES a group's raster to give its canvas footprint, so a
 *     COARSER wall takes a ratio above 1.000
 *   - the field is an integer in thousandths, range 100..10000
 *   - an out-of-range write is DISCARDED by the device, not clamped
 *   - the footprint FLOORS, so 1080 x 1.234 is 1332 and not 1333
 *
 * All four were established by driving a LivePremier simulator, not read out of
 * the manual, and they are pinned by tests upstream.
 *
 * \`npm run sync:pitch-engine\` re-copies it and rewrites the header above;
 * \`test/vendor.test.js\` fails when the copy has drifted from an upstream
 * checkout, and skips when there is not one to compare with.
 *
 * Edits belong upstream, in aquilon-pitch's \`src/lib/\`.
${MARKER}`;

await writeFile(dest, header + '\n\n' + source);
console.log(`synced from ${upstreamFile}`);
console.log(`  commit ${commit}`);
console.log(`  sha256 ${hash}`);
