/*
 * Re-build Test Card's pattern engine from a test-card checkout.
 *
 *   npm run sync:test-card                  looks in ../test-card
 *   npm run sync:test-card -- /path/to/repo
 *
 * The Test Card plugin draws Test Card's patterns — SMPTE RP 219 bars, grids,
 * alignment, LED tiles, the rulers and the life-size dinosaurs — for the
 * switcher's own outputs and canvases. Test Card already draws them, and its
 * bars are held to ffmpeg's to the code value; a second set of painters here
 * would be a second, untested opinion of what 75 % yellow is. So this repo
 * borrows the first, the way the Background Slicer borrows output-map's Arena
 * writer.
 *
 * Test Card is TypeScript and React, and does not build a consumer artefact.
 * Its `src/engine.ts` is the part with no React behind it (its own
 * `engine.test.ts` holds the import graph to that), and this script bundles it
 * with the bundler Test Card already has installed (`node_modules/rolldown`,
 * Vite's). Nothing is added to this repo's own `package.json` — it has no
 * dependencies and keeps none.
 *
 * `MANIFEST.json` records the upstream commit, the SHA-256 of every source
 * file that went into the bundle and of the bundle itself, so
 * `test/vendor.test.js` can tell a deliberate sync from an edit in place.
 * The commit must be on the upstream's main: Test Card is public
 * (stoatworks-labs/test-card), and an unpushed commit would be a source nobody
 * else can read.
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { join, dirname, resolve, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const destDir = join(here, '..', 'src', 'vendor', 'test-card');
const upstreamRepo = resolve(process.argv[2] || join(here, '..', '..', 'test-card'));
const ENTRY = 'src/engine.ts';

const sha = (buf) => createHash('sha256').update(buf).digest('hex');
const git = (...args) => execFileSync('git', ['-C', upstreamRepo, ...args], { encoding: 'utf8' }).trim();

let commit = 'unknown';
try {
  commit = git('rev-parse', 'HEAD');
  if (git('status', '--short', '--', 'src').length > 0) {
    console.error('! upstream src/ has uncommitted changes — commit there first');
    process.exit(1);
  }
} catch {
  console.error(`! no git checkout at ${upstreamRepo} — is test-card beside this repo?`);
  process.exit(1);
}
try {
  git('merge-base', '--is-ancestor', commit, 'origin/main');
} catch {
  if (!process.env.LPP_SYNC_UNPUSHED) {
    console.error(`! ${commit.slice(0, 12)} is not on test-card's origin/main — push it first`);
    console.error('  (LPP_SYNC_UNPUSHED=1 to build from it anyway, for a trial)');
    process.exit(1);
  }
}

let rolldown;
try {
  ({ rolldown } = await import(pathToFileURL(join(upstreamRepo, 'node_modules', 'rolldown', 'dist', 'index.mjs')).href));
} catch {
  console.error('! test-card has no node_modules/rolldown — run `npm ci` in the test-card checkout first');
  process.exit(1);
}

const bundle = await rolldown({ input: join(upstreamRepo, ENTRY), cwd: upstreamRepo, logLevel: 'warn' });
const { output } = await bundle.generate({ format: 'esm', minify: false });
await bundle.close();
const chunk = output.find((o) => o.type === 'chunk' && o.isEntry);
if (!chunk) {
  console.error('! the bundle has no entry chunk');
  process.exit(1);
}
if (output.some((o) => o.type === 'chunk' && !o.isEntry)) {
  console.error('! the bundle split into chunks — engine.ts must not import() anything');
  process.exit(1);
}

/* Every source file that went in, plus the type declarations they lean on —
   a type change alone can mean a semantic one. */
const sources = {};
const ids = [...chunk.moduleIds.filter((id) => id.startsWith(upstreamRepo)), join(upstreamRepo, 'src', 'types.ts')];
for (const id of [...new Set(ids)].sort()) sources[relative(upstreamRepo, id)] = sha(await readFile(id));
const license = await readFile(join(upstreamRepo, 'LICENSE'), 'utf8');
const version = JSON.parse(await readFile(join(upstreamRepo, 'package.json'), 'utf8')).version;

const header = `/* ---------------------------------------------------------------------------
 * VENDORED — do not edit this file here.
 *
 * Upstream:  test-card ${version} (github.com/stoatworks-labs/test-card)  ${ENTRY}
 * Commit:    ${commit}
 * Synced:    ${new Date().toISOString().slice(0, 10)}
 * Built by:  tools/sync-test-card.mjs with test-card's own rolldown
 *
 * Test Card's pattern settings, painters and canvas limits. The SMPTE RP 219
 * bars are computed from their R'G'B' definitions and held upstream to
 * ffmpeg's to the code value (test-card docs/rp219.md); the novelty patterns
 * are tested upstream for periodicity and scale. Nothing in this file has
 * been seen on a switcher's output — see plugins/test-card/ for what has.
 *
 * Edits belong upstream, in test-card's src/.
 *
${license.trim().split('\n').map((l) => (' * ' + l).trimEnd()).join('\n')}
 * ------------------------------------------------------------------------- */`;

const body = `${header}\n\n${chunk.code}`;
await mkdir(destDir, { recursive: true });
await writeFile(join(destDir, 'engine.js'), body);
const manifest = {
  upstream: 'test-card',
  published: false,
  repository: 'https://github.com/stoatworks-labs/test-card',
  version,
  entry: ENTRY,
  commit,
  synced: new Date().toISOString().slice(0, 10),
  license: 'MIT',
  sources,
  files: { 'engine.js': sha(body) }
};
await writeFile(join(destDir, 'MANIFEST.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`built ${ENTRY} from ${upstreamRepo}`);
console.log(`  commit ${commit}`);
console.log(`  ${Object.keys(sources).length} source files, ${Math.round(body.length / 1024)} KiB`);
