/*
 * Generate docs/OSC.md from the dictionary the resolver actually uses.
 *
 *   npm run gen:osc-docs
 *
 * ## Why this is generated
 *
 * A published address space is a promise to somebody building a TouchOSC
 * layout or a QLab cue list, and they have no way to check it short of trying
 * every address at a switcher. A hand-written document would describe
 * addresses the resolver does not answer within one firmware, and there would
 * be nothing to notice — which is the worst kind of documentation bug, because
 * the reader believes it.
 *
 * So the table comes from `oscDictionary(PARAMS)`, the same call the console
 * resolves against, and `test/osc.test.js` fails when the checked-in file
 * stops matching what this produces. Editing the prose is fine; editing the
 * table is not, and the test says so.
 *
 * The prose above and below the table is written by hand, because the five
 * rules and the reasons behind them are not derivable from a parameter list.
 * It lives in this file rather than in a template so that there is one place
 * to look.
 */

import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { oscDictionary, OSC_ROOT, VERIFIED_FIRMWARE } from '../src/vendor/mynah-lang.mjs';
import { PARAMS, PROVENANCE } from '../src/core/osc-dictionary.js';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'docs', 'OSC.md');

/** Escape a cell so a pipe in an address cannot break the table. */
const cell = (s) => String(s).replace(/\|/g, '\\|');

export function generate() {
  const entries = oscDictionary(PARAMS);

  /* Grouped in the order the generator emits them, not alphabetically: the
     dictionary is meant to be read top to bottom the first time, and takes and
     memories are what somebody wires up before they touch a layer parameter. */
  const groups = [];
  for (const e of entries) {
    let g = groups.find((x) => x.name === e.group);
    if (!g) groups.push((g = { name: e.group, rows: [] }));
    g.rows.push(e);
  }

  const lines = [];
  lines.push(HEADER.trim());
  lines.push('');
  lines.push(`> Generated by \`tools/gen-osc-docs.mjs\` — do not edit the tables by hand.`);
  lines.push('> Layer and screen-group parameters come from the control surface’s own');
  lines.push(`> catalogue, read off a **${PROVENANCE.device}** (${PROVENANCE.layerCount} layer`);
  lines.push(`> parameters, ${PROVENANCE.groupCount} screen-group). Everything else is verified`);
  lines.push(`> against LivePremier firmware **${VERIFIED_FIRMWARE}**.`);
  lines.push('');
  lines.push(`**${entries.length} addresses.**`);
  lines.push('');

  for (const g of groups) {
    lines.push(`## ${g.name}`);
    lines.push('');
    lines.push('| Address | Argument | What it does |');
    lines.push('|---|---|---|');
    for (const r of g.rows) {
      lines.push(`| \`${cell(r.address)}\` | ${cell(r.args)} | ${cell(r.summary)} |`);
    }
    lines.push('');
  }

  lines.push(FOOTER.trim());
  lines.push('');
  return lines.join('\n');
}

const HEADER = `
# The OSC dictionary

Every address LivePremier Plus answers, what it takes, and what it does.

Send OSC over UDP to the port set in **Settings → OSC input**. It is off by
default, and it binds to loopback unless told otherwise — this port fires takes
on a video switcher.

\`\`\`text
${OSC_ROOT}/screen/1/take
${OSC_ROOT}/screen/1/memory/5/recall/preview
${OSC_ROOT}/master/memory/12/store
${OSC_ROOT}/screen/1/preset/a/layer/2/opacity/opacity 128
${OSC_ROOT}/screen/1/preset/a/layer/2/opacity/opacity/norm 0.5
${OSC_ROOT}/screen/1/group/control/takeUpTime 20
\`\`\`

The same addresses work typed at the Console, which is the quickest way to try
one before wiring a surface to it.

---

## The five rules

**1. The address is the target; the argument is only the value.** Everything
about *what* is addressed is in the path, so a button with a fixed address and
no argument still means something specific. That is the difference between a
TouchOSC layout you can draw once and one that needs logic behind every
control.

**2. A trigger fires on a non-zero argument, and on no argument at all.**
Surfaces send \`1\` on press and \`0\` on release. A take that fired on both would
fire twice per press, and the second one is the one nobody meant. A release is
logged as *released, nothing sent* rather than dropped, so a surface sending
something correctly ignored still shows up.

**3. A recall never defaults to program.** \`${OSC_ROOT}/screen/1/memory/5/recall\`
goes to preview. Reaching air always costs the explicit word — the same rule
the Mynah command language keeps, for the same reason: an under-specified
command must not be able to change what is on screen.

**4. Units are the device's, unless the address ends \`/norm\`.** A fader sends
0..1; the device wants 0–256 for opacity and −2000000..2000000 for a position.
Which one \`0.5\` means cannot be worked out from the value — it is a perfectly
good literal \`posH\` *and* the middle of a fader's throw — so it is said in the
address. \`/norm\` scales across the parameter's own range; without it the value
goes as given and is clamped to that range.

**5. \`preview\` and \`program\` are resolved, never assumed.** They name whichever
preset buffer is pending or live right now, and a take swaps them.

> ⚠️ **Over UDP, only \`/a\`, \`/b\` and \`/c\` work for live layer parameters.**
> Resolving \`preview\` or \`program\` needs the device's take state, and the OSC
> listener holds no store mirror — so it refuses those addresses with that
> reason rather than guessing. A layer move that landed in whichever buffer
> happened to be live is exactly the failure rule 5 exists to prevent. The
> Console *can* resolve them, because the page has the store.

### Not implemented, and reserved

There is no relative form. A relative step needs the current value, which makes
it a property of the surface holding the encoder rather than of the address
space. \`/rel\` is refused by name, so the reserved tail explains itself instead
of looking like a typo.

---

## Types, and what happens to them

| Sent as | Read as |
|---|---|
| \`i\` int32, \`h\` int64 | a number |
| \`f\` float32, \`d\` float64 | a number |
| \`s\` string | a string — enum values are sent by name, e.g. \`LIVE_3\` |
| \`T\` / \`F\` | true / false |
| \`I\` impulse | a press |
| \`N\` nil | null |

Bundles are unpacked and their contents run. **Timetags are ignored** — waiting
on a clock this machine does not share would make a video cue fire late because
two computers disagree about the time, which is worse than firing it now.

An enum may also be given as an integer index, because a button on a surface
has nowhere to put a name. Names are matched case-insensitively; an index is
bounds-checked. A value the device does not have is refused rather than
rounded to the nearest one.

Nothing is ever sent back. This listens; it does not answer.

---
`;

const FOOTER = `
---

## How a message reaches the switcher

\`\`\`text
  QLab / TouchOSC / Companion / a lighting desk
       │  UDP
       ▼
  server/osc.js  ──decode──▶ the resolver ──▶ store paths
       │
       ▼  AWJ, TCP 10606
  the switcher
\`\`\`

Writes go out over **AWJ**, the vendor's own control protocol, rather than
through a browser tab. The point of a show-control input is that it works when
nobody is looking at it: a cue fires at 20:03 whether or not an operator
happens to have a Web RCS tab open.

Two consequences:

- **The device's AWJ port has to be on.** It can be switched off in the Web RCS
  security settings, and when it is, every OSC message fails with the same
  connection error. Check that first.
- **The device allows five AWJ clients** and counts them. This opens one
  connection per exchange and closes it, so it holds none of that budget
  between messages — but the budget is shared with everything else on the
  network.

## Getting the address right

The quickest check is the Console: type the address, and the compiled write is
shown before you press Enter. A refusal names what it did not understand.

For a sender you cannot easily change, **Settings → OSC input** counts what
arrived, what was written and what was refused, and the Console log carries
each message with the reason when one was rejected.
`;

/* Only write when run as a script. `test/osc.test.js` imports `generate()` to
   compare against the checked-in file, and a test that rewrote the file it was
   about to check would agree with itself every time. */
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const generated = generate();
  await writeFile(out, generated, 'utf8');
  console.log(`wrote ${out} — ${generated.split('\n').length} lines`);
}

export const OUT = out;
