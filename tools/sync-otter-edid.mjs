/*
 * Re-copy the Otter EDID editor's embeddable build from an otter-edid-editor
 * checkout.
 *
 * The EDID plugin builds EDIDs — from the switcher's custom formats, and in a
 * full editor beside the EDID page. EDID is exactly the kind of format that
 * gets re-typed slightly wrong in a second place: a DTD's 12-bit fields, the
 * 10 kHz clock step, the CTA encoder that is not lossless, a mosaic tile that
 * must never pass through it. Otter already pins all of that with tests, so
 * this repo borrows the result rather than re-deriving it.
 *
 *   npm run sync:otter-edid                  looks in ../otter-edid-editor
 *   npm run sync:otter-edid -- /path/to/repo
 *
 * Otter is TypeScript and React with a Vite build; this repo has neither.
 * Same arrangement as aquilon-pitch: `npm run build:embed` there emits
 * `dist-embed/otter-edid-embed.js`, one unminified dependency-free ES module
 * with React and the stylesheet inside it, committed upstream — and we vendor
 * that, not the sources.
 *
 * Same contract as the other sync tools: rewrite the provenance header with the
 * upstream commit and a content hash, so `test/vendor.test.js` can tell a
 * deliberate sync from silent drift.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dest = join(here, '..', 'src', 'vendor', 'otter-edid-embed.js');
const upstreamRepo = resolve(process.argv[2] || join(here, '..', '..', 'otter-edid-editor'));
const upstreamFile = join(upstreamRepo, 'dist-embed', 'otter-edid-embed.js');

let source;
try {
  source = await readFile(upstreamFile, 'utf8');
} catch {
  console.error(`! no ${upstreamFile}`);
  console.error('  run `npm run build:embed` in the otter-edid-editor checkout first');
  process.exit(1);
}

const hash = createHash('sha256').update(source).digest('hex');

let commit = 'unknown';
let dirty = false;
try {
  commit = execFileSync('git', ['-C', upstreamRepo, 'log', '-1', '--format=%H', '--', 'dist-embed'],
    { encoding: 'utf8' }).trim();
  dirty = execFileSync('git', ['-C', upstreamRepo, 'status', '--short', '--', 'dist-embed'],
    { encoding: 'utf8' }).trim().length > 0;
} catch {
  console.warn('! upstream is not a git checkout; recording commit as unknown');
}

/* Syncing from a modified working copy records a commit that does not contain
   what was copied. Refuse rather than write a provenance line that lies. */
if (dirty) {
  console.error('! upstream dist-embed/ has uncommitted changes — commit there first');
  process.exit(1);
}

const MARKER = ' * ------------------------------------------------------------------------- */';

const header = `/* ---------------------------------------------------------------------------
 * VENDORED — do not edit this file here.
 *
 * Upstream:  stoatworks-labs/otter-edid-editor  dist-embed/otter-edid-embed.js
 * Commit:    ${commit}
 * Synced:    ${new Date().toISOString().slice(0, 10)}
 * sha256:    ${hash}
 *
 * The Otter EDID editor, built from otter-edid-editor's src/embed.tsx: React,
 * the editor and its stylesheet in one module. Two surfaces —
 *
 *   mount(el, host)        the whole editor, with a "Save to" panel that writes
 *                          through the host (plugins/edid/popout.js is the host)
 *   edidForTiming(timing)  an EDID around a timing that is already decided —
 *                          every porch kept, the CTA VIC carried when the raster
 *                          is exactly one
 *   describeEdid(bytes)    name, preferred mode and errors, for a bank slot
 *
 * Its stylesheet styles \`body\`, so it is only ever mounted in a window of its
 * own — never into the Web RCS page.
 *
 * \`npm run sync:otter-edid\` re-copies it and rewrites the header above;
 * \`test/vendor.test.js\` fails when the copy has drifted from an upstream
 * checkout, and skips when there is not one to compare with.
 *
 * Edits belong upstream, in otter-edid-editor's \`src/\`.
${MARKER}`;

await writeFile(dest, header + '\n\n' + source);
console.log(`synced from ${upstreamFile}`);
console.log(`  commit ${commit}`);
console.log(`  sha256 ${hash}`);
