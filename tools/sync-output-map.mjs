/*
 * Re-build the Resolume Arena Advanced Output writer from an output-map
 * checkout.
 *
 *   npm run sync:output-map                  looks in ../output-map
 *   npm run sync:output-map -- /path/to/repo
 *
 * The Background Slicer's live-input mode exports an Arena preset so a media
 * server's outputs land exactly on the switcher's inputs. output-map already
 * writes that file, and it is the one that was held to real Arena 7.27 files —
 * every element, attribute and parameter name it emits appears in a file Arena
 * wrote (`docs/resolume-export.md` there, `resolume-schema.test.ts`). A second
 * writer here would be a second guess at a format nobody documents, so this
 * repo borrows the first rather than re-deriving it.
 *
 * output-map is TypeScript and, unlike mynah and aquilon-pitch, does not build
 * a consumer artefact of its own. So this script bundles one, with the bundler
 * output-map already has installed (`node_modules/rolldown`, Vite's): the
 * entry is `src/lib/resolume.ts`, its exports are kept exactly, and only what
 * it imports (`geometry.ts`) comes with it. Nothing is added to this repo's
 * own `package.json` — it has no dependencies and keeps none.
 *
 * `MANIFEST.json` records the upstream commit, the SHA-256 of every source
 * file that went into the bundle and of the bundle itself, so
 * `test/vendor.test.js` can tell a deliberate sync from an edit in place, and
 * from an upstream that has moved on.
 *
 * ⚠️ output-map has **no remote** — it is a local repository on Allan's
 * machine — so the commit recorded is local, as pixelhue-bridge's was.
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { join, dirname, resolve, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const destDir = join(here, '..', 'src', 'vendor', 'output-map');
const upstreamRepo = resolve(process.argv[2] || join(here, '..', '..', 'output-map'));
const ENTRY = 'src/lib/resolume.ts';

const sha = (buf) => createHash('sha256').update(buf).digest('hex');

let commit = 'unknown';
let dirty = false;
try {
  commit = execFileSync('git', ['-C', upstreamRepo, 'log', '-1', '--format=%H', '--', 'src/lib'], { encoding: 'utf8' }).trim();
  dirty = execFileSync('git', ['-C', upstreamRepo, 'status', '--short', '--', 'src/lib', 'src/types.ts'], { encoding: 'utf8' }).trim().length > 0;
} catch {
  console.error(`! no git checkout at ${upstreamRepo} — is output-map beside this repo?`);
  process.exit(1);
}
if (dirty) {
  console.error('! upstream src/lib or src/types.ts has uncommitted changes — commit there first');
  process.exit(1);
}

let rolldown;
try {
  ({ rolldown } = await import(pathToFileURL(join(upstreamRepo, 'node_modules', 'rolldown', 'dist', 'index.mjs')).href));
} catch {
  console.error('! output-map has no node_modules/rolldown — run `npm ci` in the output-map checkout first');
  process.exit(1);
}

const bundle = await rolldown({ input: join(upstreamRepo, ENTRY), cwd: upstreamRepo, logLevel: 'warn' });
const { output } = await bundle.generate({ format: 'esm', minify: false });
await bundle.close();
const chunk = output.find((o) => o.type === 'chunk' && o.isEntry);
if (!chunk) {
  console.error('! the bundle has no entry chunk');
  process.exit(1);
}

/* Every source file that went in, plus the type declarations they lean on —
   a type change alone can mean a semantic one. */
const sources = {};
const ids = [...chunk.moduleIds.filter((id) => id.startsWith(upstreamRepo)), join(upstreamRepo, 'src', 'types.ts')];
for (const id of ids) sources[relative(upstreamRepo, id)] = sha(await readFile(id));
const license = await readFile(join(upstreamRepo, 'LICENSE'), 'utf8');

const header = `/* ---------------------------------------------------------------------------
 * VENDORED — do not edit this file here.
 *
 * Upstream:  output-map (local repository, no remote)  ${ENTRY}
 * Commit:    ${commit}
 * Synced:    ${new Date().toISOString().slice(0, 10)}
 * Built by:  tools/sync-output-map.mjs with output-map's own rolldown
 *
 * Resolume Arena's Advanced Output preset writer. Every element, attribute and
 * parameter name it emits was read off files a real Arena 7.27 wrote, and
 * output-map's resolume-schema.test.ts holds it to them. What is NOT verified
 * upstream either: no generated file has been opened in a running Arena.
 *
 * Edits belong upstream, in output-map's src/lib/.
 *
${license.trim().split('\n').map((l) => (' * ' + l).trimEnd()).join('\n')}
 * ------------------------------------------------------------------------- */`;

const body = `${header}\n\n${chunk.code}`;
await mkdir(destDir, { recursive: true });
await writeFile(join(destDir, 'resolume.js'), body);
const manifest = {
  upstream: 'output-map',
  published: false,
  entry: ENTRY,
  commit,
  synced: new Date().toISOString().slice(0, 10),
  license: 'MIT',
  sources,
  files: { 'resolume.js': sha(body) }
};
await writeFile(join(destDir, 'MANIFEST.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`built ${ENTRY} from ${upstreamRepo}`);
console.log(`  commit ${commit}`);
for (const [k, v] of Object.entries(sources)) console.log(`  ${k} ${v.slice(0, 12)}`);
